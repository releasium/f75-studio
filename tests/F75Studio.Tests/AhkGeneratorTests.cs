using F75Studio.Hotkeys;
using F75Studio.Hotkeys.Model;

namespace F75Studio.Tests;

public class AhkGeneratorTests
{
    private const string AppExe = @"C:\Apps\F75 Studio\F75Studio.exe";
    private readonly AhkGenerator _generator = new(AppExe);

    private string[] LinesFor(HotkeyAction action, string trigger = "^k") =>
        _generator.Generate([new Hotkey { Trigger = trigger, Action = action }]).Text.Split("\r\n");

    [Fact]
    public void Quote_escapes_backtick_quote_semicolon_and_newlines()
    {
        Assert.Equal("\"a``b`\"c`;d`ne`tf\"", AhkString.Quote("a`b\"c;d\ne\tf"));
    }

    [Fact]
    public void TryUnquote_reverses_Quote_and_returns_the_rest()
    {
        Assert.True(AhkString.TryUnquote(AhkString.Quote("a`b\"c;d\ne") + ") tail", out var value, out var rest));
        Assert.Equal("a`b\"c;d\ne", value);
        Assert.Equal(") tail", rest);
        Assert.True(AhkString.TryUnquote("'single'", out var single, out _));
        Assert.Equal("single", single);
        Assert.False(AhkString.TryUnquote("no quotes", out _, out _));
    }

    [Theory]
    [InlineData("{Left}", true, "^k::Send \"{Blind}{Left}\"")]
    [InlineData("^{Left}", false, "^k::Send \"^{Left}\"")]
    public void SendKeys_renders_Send(string keys, bool blind, string expected) =>
        Assert.Contains(expected, LinesFor(new SendKeysAction(keys, blind)));

    [Fact]
    public void Remap_renders_key_to_key() =>
        Assert.Contains("RCtrl::AppsKey", LinesFor(new RemapAction("AppsKey"), "RCtrl"));

    [Fact]
    public void TypeText_renders_SendText() =>
        Assert.Contains("^k::SendText \"line1`nline2\"", LinesFor(new TypeTextAction("line1\nline2")));

    [Fact]
    public void Run_quotes_paths_with_spaces_but_not_urls()
    {
        Assert.Contains("^k::Run \"`\"C:\\Program Files\\App\\app.exe`\" --flag\"", LinesFor(new RunAction(@"C:\Program Files\App\app.exe", "--flag")));
        Assert.Contains("^k::Run \"https://example.com/a b\"", LinesFor(new RunAction("https://example.com/a b")));
        Assert.Contains("^k::Run \"notepad.exe\"", LinesFor(new RunAction("notepad.exe")));
    }

    [Fact]
    public void Media_renders_media_key() =>
        Assert.Contains("^k::Send \"{Volume_Mute}\"", LinesFor(new MediaAction(MediaCommand.Mute)));

    [Fact]
    public void SwitchLightingProfile_runs_this_app_with_profile_argument() =>
        Assert.Contains("^k::Run \"`\"C:\\Apps\\F75 Studio\\F75Studio.exe`\" --profile `\"Gaming`\"\"", LinesFor(new SwitchLightingProfileAction("Gaming")));

    [Fact]
    public void CustomCode_renders_indented_block()
    {
        var lines = LinesFor(new CustomCodeAction("x := 1\nMsgBox x"));
        var start = Array.IndexOf(lines, "^k::");
        Assert.True(start > 0);
        Assert.Equal(new[] { "^k::", "{", "    x := 1", "    MsgBox x", "}" }, lines[start..(start + 5)]);
    }

    [Fact]
    public void Disable_renders_Return() =>
        Assert.Contains("Insert::Return", LinesFor(new DisableKeyAction(), "Insert"));

    [Fact]
    public void Disabled_hotkeys_are_skipped()
    {
        var script = _generator.Generate([new Hotkey { Trigger = "^k", Enabled = false, Action = new DisableKeyAction() }]);
        Assert.DoesNotContain("^k::", script.Text);
    }

    [Fact]
    public void Full_script_groups_scopes_and_maps_lines_to_hotkeys()
    {
        var nav = new Hotkey { Trigger = "CapsLock & h", Group = "Navigation", Action = new SendKeysAction("{Left}", true) };
        var term = new Hotkey { Trigger = "^!t", Group = "Apps", Action = new RunAction(@"C:\Program Files\Windows Terminal\wt.exe") };
        var chrome = new Hotkey { Trigger = "F13", Group = "Apps", AppScope = "chrome.exe", Action = new TypeTextAction("hi; there") };

        var script = _generator.Generate([chrome, nav, term]);

        const string expected = """
            ; Generated by F75 Studio. Do not edit: changes are overwritten when you click Apply.
            #Requires AutoHotkey v2.0
            #SingleInstance Force

            ; Navigation
            CapsLock & h::Send "{Blind}{Left}"
            ; Apps
            ^!t::Run "`"C:\Program Files\Windows Terminal\wt.exe`""

            #HotIf WinActive("ahk_exe chrome.exe")
            ; Apps
            F13::SendText "hi`; there"
            #HotIf
            """;
        Assert.Equal(expected.ReplaceLineEndings("\n"), script.Text.ReplaceLineEndings("\n").TrimEnd('\n'));
        Assert.EndsWith("\r\n", script.Text);
        Assert.Equal(nav.Id, script.LineOwners[6]);
        Assert.Equal(term.Id, script.LineOwners[8]);
        Assert.Equal(chrome.Id, script.LineOwners[12]);
        Assert.Equal(3, script.LineOwners.Count);
    }
}

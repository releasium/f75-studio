using F75Studio.Hotkeys.Model;

namespace F75Studio.Hotkeys;

/// <param name="Text">Full script, CRLF line endings.</param>
/// <param name="LineOwners">1-based line number → id of the hotkey that produced it.</param>
public sealed record GeneratedScript(string Text, IReadOnlyDictionary<int, Guid> LineOwners);

public sealed class AhkGenerator
{
    public const string Header = "; Generated by F75 Studio. Do not edit: changes are overwritten when you click Apply.";

    private readonly string _appExecutablePath;

    public AhkGenerator(string appExecutablePath) => _appExecutablePath = appExecutablePath;

    public GeneratedScript Generate(IEnumerable<Hotkey> hotkeys)
    {
        var lines = new List<string> { Header, "#Requires AutoHotkey v2.0", "#SingleInstance Force" };
        var owners = new Dictionary<int, Guid>();
        var enabled = hotkeys.Where(h => h.Enabled).ToList();

        var scopes = enabled
            .Select(h => NormalizeScope(h.AppScope))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(s => s is null ? 0 : 1)
            .ThenBy(s => s, StringComparer.OrdinalIgnoreCase);

        foreach (var scope in scopes)
        {
            lines.Add("");
            if (scope is not null) lines.Add($"#HotIf WinActive({AhkString.Quote("ahk_exe " + scope)})");

            string? group = null;
            foreach (var hotkey in enabled.Where(h => string.Equals(NormalizeScope(h.AppScope), scope, StringComparison.OrdinalIgnoreCase)))
            {
                if (hotkey.Group != group)
                {
                    group = hotkey.Group;
                    lines.Add($"; {group}");
                }
                foreach (var line in Render(hotkey))
                {
                    lines.Add(line);
                    owners[lines.Count] = hotkey.Id;
                }
            }

            if (scope is not null) lines.Add("#HotIf");
        }

        return new GeneratedScript(string.Join("\r\n", lines) + "\r\n", owners);
    }

    private static string? NormalizeScope(string? scope) => string.IsNullOrWhiteSpace(scope) ? null : scope.Trim();

    private IEnumerable<string> Render(Hotkey hotkey)
    {
        var t = hotkey.Trigger.Trim();
        switch (hotkey.Action)
        {
            case SendKeysAction a:
                yield return $"{t}::Send {AhkString.Quote((a.Blind ? "{Blind}" : "") + a.Keys)}";
                break;
            case RemapAction a:
                yield return $"{t}::{a.TargetKey.Trim()}";
                break;
            case TypeTextAction a:
                yield return $"{t}::SendText {AhkString.Quote(a.Text)}";
                break;
            case RunAction a:
                yield return $"{t}::Run {AhkString.Quote(RunCommand(a.Target, a.Arguments))}";
                break;
            case MediaAction a:
                yield return $"{t}::Send {AhkString.Quote(MediaKeys.ToSendKey(a.Command))}";
                break;
            case SwitchLightingProfileAction a:
                yield return $"{t}::Run {AhkString.Quote(RunCommand(_appExecutablePath, $"--profile \"{a.ProfileName}\""))}";
                break;
            case CustomCodeAction a:
                yield return $"{t}::";
                yield return "{";
                foreach (var line in a.Code.ReplaceLineEndings("\n").Split('\n'))
                    yield return line.Length == 0 ? "" : "    " + line;
                yield return "}";
                break;
            case DisableKeyAction:
                yield return $"{t}::Return";
                break;
            default:
                throw new NotSupportedException($"Unknown action {hotkey.Action.GetType().Name}");
        }
    }

    private static string RunCommand(string target, string? arguments)
    {
        var quoted = target.Contains(' ') && !target.Contains("://") ? $"\"{target}\"" : target;
        return string.IsNullOrWhiteSpace(arguments) ? quoted : $"{quoted} {arguments.Trim()}";
    }
}

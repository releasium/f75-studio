using CommunityToolkit.Mvvm.ComponentModel;
using F75Studio.Hotkeys;

namespace F75Studio.App.ViewModels;

public sealed partial class ScriptItemViewModel : ObservableObject
{
    private readonly Action<ScriptItemViewModel, bool> _onRunAtStartupChanged;

    [ObservableProperty] private bool _isRunning;
    [ObservableProperty] private bool _runAtStartup;

    public ScriptItemViewModel(ScriptInfo info, bool isGenerated, bool isRunning, bool runAtStartup, Action<ScriptItemViewModel, bool> onRunAtStartupChanged)
    {
        Path = info.Path;
        Name = info.Name;
        Folder = System.IO.Path.GetDirectoryName(info.Path) ?? "";
        IsGenerated = isGenerated;
        _isRunning = isRunning;
        _runAtStartup = runAtStartup;
        _onRunAtStartupChanged = onRunAtStartupChanged;
    }

    public string Path { get; }
    public string Name { get; }
    public string Folder { get; }

    /// <summary>True for Documents\F75Studio\hotkeys.ahk, which is regenerated by the builder and always auto-started.</summary>
    public bool IsGenerated { get; }

    public bool CanRunAtStartup => !IsGenerated;

    partial void OnRunAtStartupChanged(bool value) => _onRunAtStartupChanged(this, value);
}
